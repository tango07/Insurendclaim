import { useState } from "react";
import { api, ApiError, CATEGORY_OPTIONS, type Asset, type Attachment, type Claim, type Guidance, type PolicySummary } from "../api";
import { Alert, money, SourceTag, Spinner } from "./ui";

const lines = (s: string) => s.split("\n").map((x) => x.trim()).filter(Boolean);

interface Props {
  policyholderId: string;
  policy: PolicySummary;
  asset: Asset;
  description: string;
  attachments: Attachment[];
  answeredKeys: string[];
  guidance: Guidance | null; // null = manual entry (AI unavailable)
  onSubmitted: (claim: Claim) => void;
}

/** Editable AI suggestion. Every block is tagged with where it came from. */
export default function ClaimReview({ policyholderId, policy, asset, description, attachments, answeredKeys, guidance, onSubmitted }: Props) {
  const [category, setCategory] = useState(guidance?.suggested_category ?? "other");
  const [summary, setSummary] = useState(guidance?.incident_summary ?? description.slice(0, 1500));
  const [steps, setSteps] = useState((guidance?.next_steps ?? ["An adjuster will contact you to confirm details"]).join("\n"));
  const [docs, setDocs] = useState((guidance?.documents_to_collect ?? ["Photos of the damage"]).join("\n"));
  const [confirmed, setConfirmed] = useState(false);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<string | null>(null);
  const [done, setDone] = useState(false);

  async function submit() {
    setError(null);
    if (summary.trim().length < 10) return setError("The summary needs at least 10 characters.");
    setBusy(true);
    try {
      const c = await api.submit({
        policyholder_id: policyholderId, policy_id: policy.id, asset_id: asset.id, description, attachment_ids: attachments.map((a) => a.id),
        answered_keys: answeredKeys, category, summary: summary.trim(), next_steps: lines(steps), documents_to_collect: lines(docs), ai_suggestion: guidance,
      });
      setDone(true);
      onSubmitted(c);
    } catch (e) {
      setError((e as ApiError).message);
    } finally {
      setBusy(false);
    }
  }

  return (
    <section className="space-y-4" aria-labelledby="review-h" data-testid="claim-review">
      <div>
        <h3 id="review-h" className="font-semibold">Your claim summary: review and edit</h3>
        <p className="text-xs text-slate-600">For <strong>{asset.name}</strong> · {policy.product_name} ({policy.insurer.short_name}) · <span className="font-mono">{policy.policy_number}</span></p>
      </div>

      {guidance ? (
        <>
          <Alert tone="info" title="Guidance, not a decision">{guidance.disclaimer}</Alert>
          {guidance.provider === "mock" && (
            <p className="text-xs text-slate-500" data-testid="mock-note">
              Generated by the rule-based mock{guidance.fallback_reason ? `: ${guidance.fallback_reason}` : " (no AI key configured)."}
            </p>
          )}
          {guidance.limitations.length > 0 && (
            <Alert tone="warn" title={guidance.needs_adjuster_review ? "Limitations: an adjuster should review" : "Limitations"}>
              <ul className="list-disc pl-5">{guidance.limitations.map((l) => <li key={l}>{l}</li>)}</ul>
            </Alert>
          )}
        </>
      ) : (
        <Alert tone="warn">AI guidance isn't available, so please fill in the claim yourself. An adjuster will review it.</Alert>
      )}

      <div className="grid gap-3 sm:grid-cols-2">
        <div>
          <div className="mb-1 flex items-center gap-2"><label htmlFor="cat" className="label mb-0">Claim category</label>{guidance && <SourceTag source="ai" />}</div>
          <select id="cat" className="input" value={category} onChange={(e) => setCategory(e.target.value)} disabled={done}>
            {(CATEGORY_OPTIONS[policy.policy_type] ?? CATEGORY_OPTIONS.gadget).map(([k, l]) => <option key={k} value={k}>{l}</option>)}
          </select>
          {guidance && <p className="mt-1 text-xs text-slate-500">Confidence: {guidance.category_confidence}</p>}
        </div>
      </div>

      <div>
        <div className="mb-1 flex items-center gap-2"><label htmlFor="sum" className="label mb-0">Incident summary</label>{guidance && <SourceTag source="ai" />}</div>
        <textarea id="sum" className="input min-h-[90px]" value={summary} maxLength={1500} onChange={(e) => setSummary(e.target.value)} disabled={done} data-testid="summary" />
        <details className="mt-1 text-xs text-slate-500">
          <summary className="cursor-pointer">What you told me (kept with the claim, unchanged) <SourceTag source="user" /></summary>
          <p className="mt-1 whitespace-pre-wrap text-slate-700">{description}</p>
        </details>
      </div>

      {guidance && (
        <div>
          <div className="mb-2 flex items-center gap-2"><h4 className="text-sm font-medium">Potentially relevant cover</h4><SourceTag source="policy" /></div>
          {guidance.relevant_coverages.length === 0 ? (
            <p className="text-sm text-slate-600">No matching cover found in the sample policy wording. An adjuster will confirm.</p>
          ) : (
            <ul className="space-y-2">
              {guidance.relevant_coverages.map((c) => (
                <li key={c.coverage_code} className="rounded-lg border border-slate-200 bg-white p-3 text-sm">
                  <p className="font-medium">{c.coverage_name} <span className="font-mono text-xs text-slate-500">{c.coverage_code}</span></p>
                  <p className="mt-1 text-slate-700">"{c.policy_wording}"</p>
                  <p className="mt-1 text-xs text-slate-600">Limit: {c.limit_note ?? "n/a"} · Deductible: {money(c.deductible_amount)}</p>
                  <p className="mt-1 text-xs text-violet-800"><span className="font-medium">Why it may apply (AI):</span> {c.why_relevant}</p>
                </li>
              ))}
            </ul>
          )}
          {guidance.possible_exclusions.length > 0 && (
            <div className="mt-3">
              <h4 className="text-sm font-medium">Exclusions that could matter</h4>
              <ul className="mt-1 list-disc space-y-1 pl-5 text-sm text-slate-700">
                {guidance.possible_exclusions.map((e) => <li key={e.code}>{e.policy_wording} <span className="text-xs text-violet-800">{e.why_relevant}</span></li>)}
              </ul>
            </div>
          )}
        </div>
      )}

      {guidance && guidance.missing_information.length > 0 && (
        <div>
          <div className="mb-1 flex items-center gap-2"><h4 className="text-sm font-medium">Still worth collecting</h4><SourceTag source="ai" /></div>
          <ul className="list-disc space-y-1 pl-5 text-sm text-slate-700" data-testid="missing-info">
            {guidance.missing_information.map((m) => <li key={m}>{m}</li>)}
          </ul>
        </div>
      )}

      {guidance && (guidance.image_observations ?? []).length > 0 && (
        <div data-testid="image-observations">
          <div className="mb-1 flex items-center gap-2"><h4 className="text-sm font-medium">What the AI saw in your photos</h4><SourceTag source="ai" /></div>
          <ul className="space-y-2">
            {(guidance.image_observations ?? []).map((o) => (
              <li key={o.filename} className="rounded-lg border border-violet-200 bg-violet-50 p-3 text-sm">
                <div className="flex flex-wrap items-center justify-between gap-2">
                  <span className="font-medium">📷 {o.filename}</span>
                  <span className={`badge ${o.matches_description === "yes" ? "bg-emerald-100 text-emerald-800" : o.matches_description === "no" ? "bg-red-100 text-red-800" : "bg-amber-100 text-amber-900"}`}>
                    {o.matches_description === "yes" ? "Matches your description" : o.matches_description === "partly" ? "Partly matches" : o.matches_description === "no" ? "May not match" : "Unclear"}
                  </span>
                </div>
                <p className="mt-1 text-slate-700">{o.observation}</p>
              </li>
            ))}
          </ul>
          <p className="mt-1 text-xs text-slate-500">AI description of what is visible only. It is not a damage valuation or repair estimate; an adjuster will assess the damage.</p>
        </div>
      )}

      {guidance && guidance.attachment_notes.length > 0 && (
        <div>
          <div className="mb-1 flex items-center gap-2"><h4 className="text-sm font-medium">Attachments</h4><SourceTag source="system" /></div>
          <ul className="list-disc space-y-1 pl-5 text-sm text-slate-700">{guidance.attachment_notes.map((n) => <li key={n}>{n}</li>)}</ul>
        </div>
      )}

      <div className="grid gap-3 md:grid-cols-2">
        <div>
          <div className="mb-1 flex items-center gap-2"><label htmlFor="docs" className="label mb-0">Documents to collect</label>{guidance && <SourceTag source="ai" />}</div>
          <textarea id="docs" className="input min-h-[120px]" value={docs} onChange={(e) => setDocs(e.target.value)} disabled={done} />
        </div>
        <div>
          <div className="mb-1 flex items-center gap-2"><label htmlFor="steps" className="label mb-0">Next steps</label>{guidance && <SourceTag source="ai" />}</div>
          <textarea id="steps" className="input min-h-[120px]" value={steps} onChange={(e) => setSteps(e.target.value)} disabled={done} data-testid="steps" />
        </div>
      </div>
      <p className="-mt-2 text-xs text-slate-500">One item per line.</p>

      {!done && (
        <>
          <label className="flex items-start gap-2 text-sm">
            <input type="checkbox" className="mt-0.5" checked={confirmed} onChange={(e) => setConfirmed(e.target.checked)} data-testid="confirm" />
            I've reviewed these details. I understand this guidance is not a coverage decision.
          </label>
          {error && <Alert tone="error">{error}</Alert>}
          <div className="flex items-center gap-3">
            <button className="btn-primary" disabled={!confirmed || busy} onClick={submit} data-testid="submit-claim">Submit claim to {policy.insurer.short_name}</button>
            {busy && <Spinner label="Submitting…" />}
          </div>
        </>
      )}
    </section>
  );
}
