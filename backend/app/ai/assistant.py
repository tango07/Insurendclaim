"""Small Q&A assistant grounded in one policy (and optionally one claim)."""
from __future__ import annotations

import json
import re

from .providers import LLMProvider, ProviderError, extract_json
from .schemas import DISCLAIMER

STOP = set(("a an the is are am do does did i my me we our you your it its of to in on for and or with what how when can will would "
            "should be if this that there any have has cover covers covered coverage covering policy insurance insured claim get").split())

SYSTEM = """You answer a policyholder's question using ONLY the supplied FICTIONAL sample policy and claim data.
If the answer isn't in the data, say you don't know and suggest contacting an adjuster. Never invent terms.
Do not make coverage decisions or promise outcomes. Keep answers under 120 words, plain language.
Respond as JSON only: {"answer": str, "sources": [clause or coverage codes you used]}"""


def _words(s: str) -> set[str]:
    return {w for w in re.findall(r"[a-z]+", s.lower()) if w not in STOP and len(w) > 2}


def _clauses(policy: dict) -> list[tuple[str, str, str]]:
    out = [(c["code"], f"{c['name']}: {c['description']} Limit: {c['limit_note'] or 'n/a'}. Deductible: ${c['deductible_amount'] or 0:,.0f}.", "coverage") for c in policy["coverages"]]
    out += [(e["code"], e["text"], "exclusion") for e in policy["exclusions"]]
    out += [(c["code"], c["text"], "condition") for c in policy["conditions"]]
    return out


def _mock_answer(question: str, policy: dict, claim: dict | None) -> tuple[str, list[str]]:
    q = question.lower()
    if claim and re.search(r"\b(status|claim|next|happen|progress|when)\b", q):
        last = claim["events"][-1] if claim["events"] else None
        steps = "; ".join(claim["next_steps"][:3]) or "an adjuster will be in touch"
        return (f"Claim {claim['claim_number']} is currently '{claim['status'].replace('_', ' ')}'."
                + (f" Latest update: {last['title']}." if last else "") + f" Suggested next steps: {steps}.", [claim["claim_number"]])
    if not policy["wording_available"] or not policy["coverages"]:
        return ("The policy wording for this policy isn't loaded in the demo, so I can't say what it covers. "
                "Please contact an adjuster or your agent.", [])
    qw = _words(question)
    if "deductible" in q or "excess" in q:
        lines = [f"{c['name']}: ${c['deductible_amount'] or 0:,.0f}" for c in policy["coverages"]]
        return "Deductibles in your sample policy: " + "; ".join(lines) + ".", [c["code"] for c in policy["coverages"]]
    if "limit" in q or "maximum" in q or "how much" in q:
        lines = [f"{c['name']}: {c['limit_note']}" for c in policy["coverages"]]
        return "Limits in your sample policy: " + "; ".join(lines) + ".", [c["code"] for c in policy["coverages"]]
    scored = sorted(((len(qw & _words(text)), code, text, kind) for code, text, kind in _clauses(policy)), reverse=True)
    hits = [s for s in scored if s[0] > 0][:3]
    if not hits:
        return ("I couldn't find anything in the sample policy wording that answers that. "
                "An adjuster can confirm.", [])
    body = " ".join(f"[{kind} {code}] {text}" for _, code, text, kind in hits)
    return f"Here's what the sample policy says that may be relevant: {body}", [h[1] for h in hits]


def adjuster_answer(policy: dict, adjusters: list[dict], appointments: list[dict]) -> tuple[str, list[str]]:
    """Factual directory answer straight from the DB (never generated by the model)."""
    ins = policy["insurer"]
    parts = []
    mine = [a for a in appointments if a["policy_id"] == policy["id"] and a["status"] == "confirmed"]
    if mine:
        a = mine[-1]
        parts.append(f"Your booked adjuster is {a['adjuster_name']} ({a['reference']}), {a['slot_start'].replace('T', ' at ')}. "
                     f"Phone {a['adjuster_phone']}, email {a['adjuster_email']}.")
    if adjusters:
        lines = [f"{a['full_name']}: {a['specialization']}, {a['office_location']}, {a['phone']}, {a['email']}, languages {a['languages']}"
                 for a in adjusters]
        parts.append(f"{ins['name']} adjusters for this policy: " + "; ".join(lines) + ".")
        if not mine:
            parts.append("To book one, open ClaimAssist and choose 'Speak with an adjuster'.")
    else:
        parts.append(f"No adjusters are listed for this policy. Call {ins['short_name']} claims on {ins['claims_phone']}.")
    return " ".join(parts), [a["id"] for a in adjusters]


def answer(question: str, policy: dict, claim: dict | None, provider: LLMProvider | None,
           adjusters: list[dict] | None = None, appointments: list[dict] | None = None) -> dict:
    if re.search(r"\badjust(er|or)s?\b", question, re.I):
        text, sources = adjuster_answer(policy, adjusters or [], appointments or [])
        return {"answer": text, "sources": sources, "provider": "directory", "disclaimer": DISCLAIMER}
    if provider is None:
        text, sources = _mock_answer(question, policy, claim)
        return {"answer": text, "sources": sources, "provider": "mock", "disclaimer": DISCLAIMER}
    ctx = {"policy": {k: policy[k] for k in ("product_name", "policy_type", "status", "wording_available")},
           "coverages": [{k: c[k] for k in ("code", "name", "description", "limit_note", "deductible_amount")} for c in policy["coverages"]],
           "exclusions": [{"code": e["code"], "text": e["text"]} for e in policy["exclusions"]],
           "conditions": [{"code": c["code"], "text": c["text"]} for c in policy["conditions"]]}
    if claim:
        ctx["claim"] = {k: claim[k] for k in ("claim_number", "status", "category", "summary", "next_steps", "documents_to_collect")}
        ctx["claim"]["timeline"] = [e["title"] for e in claim["events"]]
    try:
        raw = extract_json(provider.complete(SYSTEM, f"Data:\n{json.dumps(ctx)}\n\nQuestion: {question}", max_tokens=500))
        valid = {c[0] for c in _clauses(policy)} | ({claim["claim_number"]} if claim else set())
        sources = [s for s in raw.get("sources", []) if isinstance(s, str) and s in valid]
        text = str(raw.get("answer", "")).strip()
        if not text:
            raise ProviderError("empty answer")
        return {"answer": text, "sources": sources, "provider": provider.name, "disclaimer": DISCLAIMER}
    except ProviderError:
        text, sources = _mock_answer(question, policy, claim)
        return {"answer": text + " (AI service unavailable; rule-based answer shown.)", "sources": sources,
                "provider": "mock", "disclaimer": DISCLAIMER}
